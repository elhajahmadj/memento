import { PageShell } from "@/shared/ui/shell/page-shell";
import { useIsAdmin } from "@/features/auth/presentation/role";
import {
  SwitchOrgGatePage,
  useSwitchOrgGate,
} from "@/features/auth/presentation/switch-org-gate";
import { MaintenanceSection } from "@/features/settings/presentation/sections/maintenance-section";

export function ToolsMaintenance() {
  const isAdmin = useIsAdmin();
  const { canPromptSwitch } = useSwitchOrgGate({
    allowed: isAdmin,
    requires: "admin",
    pageLabel: "Maintenance",
  });

  if (!isAdmin) {
    if (!canPromptSwitch) return null;
    return (
      <SwitchOrgGatePage
        pageLabel="Maintenance"
        description="Tidy up files generated by the recorder in the active project."
        requires="admin"
        testId="maintenance-switch-org-prompt"
        contentClassName="max-w-4xl w-full"
        backTestId="button-maintenance-back"
        backTo="/tools"
        backLabel="Back to Tools"
      />
    );
  }

  return (
    <PageShell
      contentClassName="max-w-4xl w-full"
      backTestId="button-maintenance-back"
      backTo="/tools"
      backLabel="Back to Tools"
    >
      <h1 className="text-3xl font-semibold mb-2">Maintenance</h1>
      <p className="text-muted-foreground mb-8">
        Tidy up files generated by the recorder in the active project.
      </p>
      <MaintenanceSection />
    </PageShell>
  );
}
