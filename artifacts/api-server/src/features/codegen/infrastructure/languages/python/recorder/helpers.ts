import path from "node:path";
import fs from "node:fs/promises";
import { safeJoin } from "@/features/projects/infrastructure/paths";
import type { AiRunStep } from "@/features/ai-agent/domain/types";

export function stripSuiteSuffix(s: string): string {
  return s.replace(/Tests?$/i, "");
}

export function pascal(s: string): string {
  const parts = (s ?? "").replace(/[^a-zA-Z0-9]+/g, " ").trim().split(/\s+/);
  return parts.map((w) => (w ? w.charAt(0).toUpperCase() + w.slice(1) : "")).join("");
}

export function snake(s: string): string {
  return (s ?? "")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^a-zA-Z0-9]+/g, "_")
    .toLowerCase()
    .replace(/^_+|_+$/g, "");
}

export function upperSnake(s: string): string {
  return snake(s).toUpperCase();
}

export function escapePy(v: unknown): string {
  if (v == null) return "";
  return String(v).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

export async function exists(p: string): Promise<boolean> {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

export async function writeFile(abs: string, content: string): Promise<void> {
  await fs.mkdir(path.dirname(abs), { recursive: true });
  await fs.writeFile(abs, content.endsWith("\n") ? content : content + "\n");
}

export async function ensureInit(
  projectRoot: string,
  rel: string,
  written: string[],
): Promise<void> {
  const abs = safeJoin(projectRoot, rel);
  if (!(await exists(abs))) {
    await writeFile(abs, "");
    written.push(rel);
  }
}

export function firstGotoUrl(steps: AiRunStep[]): string | null {
  for (const s of steps) {
    for (const c of s.playwrightCalls ?? []) {
      if (c.method === "page.goto" && c.args && typeof c.args[0] === "string") {
        return c.args[0];
      }
    }
  }
  return null;
}

export function inferFieldName(step: AiRunStep): string | null {
  if (step.inputs && step.inputs[0]) return step.inputs[0].field;
  const m = step.method?.name?.match(/(?:Fill|Set)([A-Z][A-Za-z0-9]*)/);
  return m ? m[1] : null;
}

/**
 * Convert a PascalCase URL name (e.g. `GoogleBaseUrl`) into the
 * UPPER_SNAKE_CASE constant we emit in `config.py`
 * (e.g. `GOOGLE_BASE_URL`). Plain `BaseUrl` becomes `BASE_URL`.
 */
export function pyConstName(pascalName: string): string {
  return pascalName
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .toUpperCase();
}

/**
 * Convert a `Given_When_Then` PascalCase identifier into the snake_case
 * function name we emit (e.g. `GivenLogin_WhenSubmit_ThenSucceeds` →
 * `given_login_when_submit_then_succeeds`).
 */
export function pySnakeName(s: string): string {
  return (s ?? "")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^a-zA-Z0-9_]+/g, "_")
    .toLowerCase()
    .replace(/^_+|_+$/g, "");
}

export function pyHeader(runId: string): string {
  return [
    `# generated by Memento AI Agent — run ${runId}`,
    `# do not edit by hand; rerun the AI Agent to refresh.`,
  ].join("\n");
}

/**
 * Compute the `.setup` sidecar path for a pytest suite file.
 * `tests/test_login.py` → `tests/test_login.setup`. The sidecar lives
 * next to the suite (same directory + stem) so `add_method` lookups
 * can find it from the user-selected suite path alone.
 */
export function pySetupSidecarPath(suiteRel: string): string {
  const dir = path.posix.dirname(suiteRel);
  const base = path.posix.basename(suiteRel);
  const stem = base.endsWith(".py") ? base.slice(0, -3) : base;
  return dir === "." ? `${stem}.setup` : `${dir}/${stem}.setup`;
}
