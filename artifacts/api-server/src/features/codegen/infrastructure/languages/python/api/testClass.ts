import { API_PYTHON_HELPER_DIR, API_PYTHON_TESTS_DIR } from "@/features/projects/infrastructure/apiPythonScaffolder";
import type { BuildApiTestSpec } from "@/features/codegen/infrastructure/apiCsharpCodegen";
import {
  categoriesClassNameForSuite,
  categoriesImportModuleForSuite,
  pytestMarkerName,
} from "@/features/codegen/infrastructure/pythonCodegen";
import { ensureTrailingNewline } from "./fileUtils";
import {
  assistantClassNameFor,
  ident,
  pyMethodName,
  pyStr,
  snakeCase,
} from "./naming";

// ─── test class rendering ───────────────────────────────────────────────

/**
 * Render the `@pytest.mark.skip(...)` and `@pytest.mark.{slug}`
 * decorator lines (in that order) for a method based on the spec's
 * RecordingMetadata pass-through fields. Returns "" when neither field
 * is set so the test method renders unchanged. Trailing newline is
 * included when at least one decorator is present so callers can
 * concatenate cleanly with the method header.
 */
function renderMethodDecoratorsPy(spec: BuildApiTestSpec): string {
  const lines: string[] = [];
  const ignoreReason = spec.metadata?.ignoreReason ?? null;
  const categoryConstantName = spec.metadata?.categoryConstantName ?? null;
  const categoryValue = spec.metadata?.categoryValue ?? null;
  if (ignoreReason) {
    lines.push(`    @pytest.mark.skip(reason=${pyStr(ignoreReason)})`);
  }
  if (categoryConstantName && categoryValue) {
    lines.push(`    @pytest.mark.${pytestMarkerName(categoryValue)}`);
  }
  return lines.length > 0 ? `${lines.join("\n")}\n` : "";
}

function renderTestMethodBody(spec: BuildApiTestSpec): string {
  const methodName = pyMethodName(spec.helperMethodName);
  const callArgs = spec.parameters.map((p) => p.name).join(", ");
  const decorators = renderMethodDecoratorsPy(spec);
  if (spec.buildInto === "oneTimeSetup") {
    return `${decorators}    def test_${snakeCase(spec.testMethodName)}(self):
        assert self._response.status_code == 200, (
            f"Status: {self._response.status_code}"
        )`;
  }
  // testMethod and perTestSetup both re-run the helper inside the test.
  return `${decorators}    async def test_${snakeCase(spec.testMethodName)}(self):
        response = await self._assistant.${methodName}(${callArgs})
        assert response.status_code == 200, f"Status: {response.status_code}"`;
}

/**
 * Build the optional `from test_categories.{snake}_categories import
 * {Suite}Categories` import line — emitted at the top of generated test
 * files when the spec carries a category. Returns "" when no category
 * is requested. Pytest markers can't reference the constant directly so
 * the import is the documented dependency that explains where the
 * marker name came from.
 */
export function categoriesImportLineFor(
  spec: BuildApiTestSpec,
  testClassName: string,
): string {
  if (!(spec.metadata?.categoryConstantName && spec.metadata?.categoryValue)) {
    return "";
  }
  // The API scaffold places the categories file at
  // `<root>/${API_PYTHON_TESTS_DIR}/test_categories/{snake}_categories.py`
  // and the root `conftest.py` puts the project root on sys.path, so
  // the import must be qualified with the tests-package name. The UI
  // codegen uses the same helper without the prefix because its files
  // sit directly under the project root.
  const baseModule = categoriesImportModuleForSuite(testClassName);
  return `from ${API_PYTHON_TESTS_DIR}.${baseModule} import ${categoriesClassNameForSuite(testClassName)}\n`;
}

/** Render a brand-new test class file content. */
export function renderNewTestClass(spec: BuildApiTestSpec): string {
  if (spec.testClass.mode !== "new") {
    throw new Error("renderNewTestClass requires mode=new");
  }
  ident(spec.testClass.className, "Test class name");
  ident(spec.testMethodName, "Test method name");
  const className = spec.testClass.className;
  const assistantClass = assistantClassNameFor(className);
  const methodName = pyMethodName(spec.helperMethodName);
  const callArgs = spec.parameters.map((p) => p.name).join(", ");

  const oneTime =
    spec.buildInto === "oneTimeSetup"
      ? `        import asyncio\n        self._response = asyncio.get_event_loop().run_until_complete(\n            self._assistant.${methodName}(${callArgs})\n        )\n`
      : "";

  const categoriesImport = categoriesImportLineFor(spec, className);

  return `"""
${className} — generated by Build Test. Each method calls one endpoint
through the per-suite assistant and asserts on the response.
"""
import pytest

from ${API_PYTHON_HELPER_DIR}.infrastructure.api_test_fixture import ApiTestFixture
from ${API_PYTHON_TESTS_DIR}.api_testing_assistants.${snakeCase(assistantClass)} import (
    ${assistantClass},
)
${categoriesImport}
pytestmark = pytest.mark.api


class ${className}:
    @pytest.fixture(autouse=True)
    def _setup(self, api_fixture: ApiTestFixture):
        self._assistant = ${assistantClass}(api_fixture)
${oneTime}
${renderTestMethodBody(spec)}
`;
}

/**
 * Insert a new test method into an existing test class file. Throws if a
 * method with the same name already exists. When the spec carries a
 * category, idempotently inserts the `{Suite}Categories` import after
 * the existing `import pytest` line so re-records don't duplicate it.
 */
export function insertMethodIntoExistingClass(
  source: string,
  spec: BuildApiTestSpec,
): string {
  ident(spec.testMethodName, "Test method name");
  if (spec.buildInto !== "testMethod") {
    throw new Error(
      "Adding to an existing test class is only supported when buildInto = testMethod",
    );
  }
  const headerRe = /^class\s+(\w+)\s*[:(]/m;
  const m = headerRe.exec(source);
  if (!m) {
    throw new Error(
      "Target test class file does not contain a recognizable class declaration",
    );
  }
  const testClassName = m[1]!;
  const dupRe = new RegExp(
    `^[ \\t]{4}(?:async\\s+)?def\\s+test_${snakeCase(spec.testMethodName)}\\s*\\(`,
    "m",
  );
  if (dupRe.test(source)) {
    throw new Error(
      `Test method ${spec.testMethodName} already exists in target class`,
    );
  }

  let working = source;
  if (spec.metadata?.categoryConstantName && spec.metadata?.categoryValue) {
    const importLine = categoriesImportLineFor(spec, testClassName).replace(
      /\n$/,
      "",
    );
    if (importLine && !working.split("\n").some((l) => l.trim() === importLine)) {
      const lines = working.split("\n");
      let insertAt = -1;
      for (let i = 0; i < lines.length; i++) {
        if (/^import\s+pytest\s*$/.test(lines[i]!.trim())) {
          insertAt = i + 1;
          break;
        }
      }
      if (insertAt === -1) insertAt = 0;
      lines.splice(insertAt, 0, importLine);
      working = lines.join("\n");
    }
  }

  const trimmed = working.replace(/\n+$/, "");
  return ensureTrailingNewline(`${trimmed}\n\n${renderTestMethodBody(spec)}\n`);
}
