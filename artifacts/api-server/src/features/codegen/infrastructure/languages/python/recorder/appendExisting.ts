import fs from "node:fs/promises";
import { renderPyTest, type PyTestArgs } from "./testRendering";

/**
 * Append a freshly-rendered AI-authored test into an existing pytest
 * suite file. Imports from the new test are merged into the existing
 * import block (deduped); the test function body is appended at EOF
 * preceded by a single blank-line separator and the AI-Agent header
 * comment so reviewers can see which run authored the addition.
 */
export async function appendToExistingPyTest(
  absPath: string,
  runId: string,
  args: PyTestArgs,
): Promise<void> {
  const fullRendered = renderPyTest(args);
  const { imports, body } = splitPyTestRendered(fullRendered);
  const existing = await fs.readFile(absPath, "utf8");
  const merged = mergePyImports(existing, imports);
  const trimmed = merged.replace(/\s+$/, "");
  const addition = [
    "",
    "",
    `# generated by Memento AI Agent — run ${runId}`,
    body.trim(),
    "",
  ].join("\n");
  await fs.writeFile(absPath, trimmed + addition);
}

/**
 * Split a freshly-rendered pytest module into its top-of-file import
 * block and the rest (header comments + test function/class). The
 * renderer always emits `header\n\nimports\n\nbody`, so we walk past
 * the header comments, collect contiguous `import` / `from … import`
 * lines, then treat everything after the blank separator as the body.
 */
export function splitPyTestRendered(rendered: string): {
  imports: string[];
  body: string;
} {
  const lines = rendered.split("\n");
  const imports: string[] = [];
  const bodyLines: string[] = [];
  let inImports = false;
  let afterImports = false;
  for (let i = 0; i < lines.length; i++) {
    const ln = lines[i]!;
    if (afterImports) {
      bodyLines.push(ln);
      continue;
    }
    const trimmed = ln.trim();
    if (!inImports) {
      if (trimmed.startsWith("#") || trimmed === "") continue;
      if (trimmed.startsWith("import ") || trimmed.startsWith("from ")) {
        inImports = true;
        imports.push(trimmed);
        continue;
      }
      // Body started without any imports — capture remainder.
      bodyLines.push(...lines.slice(i));
      afterImports = true;
      continue;
    }
    if (trimmed.startsWith("import ") || trimmed.startsWith("from ")) {
      imports.push(trimmed);
      continue;
    }
    if (trimmed === "") continue;
    bodyLines.push(...lines.slice(i));
    afterImports = true;
  }
  return { imports, body: bodyLines.join("\n") };
}

/**
 * Add any imports from `additions` that are not already present in
 * `existing` (line-equal match, ignoring whitespace). Inserts new
 * imports immediately after the last existing top-level import line;
 * when the existing file has no imports at all, prepends a fresh
 * import block before the rest of the file.
 */
export function mergePyImports(existing: string, additions: string[]): string {
  if (additions.length === 0) return existing;
  const lines = existing.split("\n");
  const present = new Set<string>();
  let lastImportIdx = -1;
  for (let i = 0; i < lines.length; i++) {
    const t = lines[i]!.trim();
    if (t.startsWith("import ") || t.startsWith("from ")) {
      present.add(t);
      lastImportIdx = i;
    }
  }
  const missing = additions.filter((a) => !present.has(a));
  if (missing.length === 0) return existing;
  if (lastImportIdx === -1) {
    return missing.join("\n") + "\n\n" + existing;
  }
  lines.splice(lastImportIdx + 1, 0, ...missing);
  return lines.join("\n");
}
