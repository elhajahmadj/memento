import fs from "node:fs/promises";
import path from "node:path";
import { safeJoin } from "@/features/projects/infrastructure/paths";
import type { AiRunReport, AiRunStep } from "@/features/ai-agent/domain/types";
import { deriveUrlName } from "@/features/ai-agent/infrastructure/urlNaming";

export const HEADER = (runId: string): string =>
  `// <auto-generated>\n// Memento AI Agent — run ${runId}\n// Re-run the AI Agent to refresh the AI-authored portions.\n// </auto-generated>`;

export async function exists(abs: string): Promise<boolean> {
  try {
    await fs.access(abs);
    return true;
  } catch {
    return false;
  }
}

export async function writeFileSafe(
  projectRoot: string,
  rel: string,
  content: string,
): Promise<void> {
  const abs = safeJoin(projectRoot, rel);
  await fs.mkdir(path.dirname(abs), { recursive: true });
  await fs.writeFile(abs, content.endsWith("\n") ? content : content + "\n");
}

export async function readJsonSafe(
  abs: string,
): Promise<Record<string, unknown> | null> {
  try {
    const txt = await fs.readFile(abs, "utf8");
    const parsed = JSON.parse(txt);
    return parsed && typeof parsed === "object" ? (parsed as Record<string, unknown>) : null;
  } catch {
    return null;
  }
}

export async function upsertNamedUrls(
  abs: string,
  named: Map<string, string>,
): Promise<boolean> {
  if (named.size === 0) return false;
  let json: Record<string, unknown> = {};
  try {
    const txt = await fs.readFile(abs, "utf8");
    try {
      json = JSON.parse(txt) as Record<string, unknown>;
    } catch {
      // Don't clobber malformed appsettings.json.
      return false;
    }
  } catch {
    // missing — we'll create it
  }
  const urls = (json["Urls"] as Record<string, unknown> | undefined) ?? {};
  let changed = false;
  for (const [name, url] of named.entries()) {
    const existing = urls[name];
    if (typeof existing === "string" && existing.trim().length > 0) continue;
    urls[name] = url;
    changed = true;
  }
  if (!changed) return false;
  json["Urls"] = urls;
  await fs.mkdir(path.dirname(abs), { recursive: true });
  await fs.writeFile(abs, JSON.stringify(json, null, 2) + "\n");
  return true;
}

/**
 * Resolve URL → typed property name. Prefers the per-URL names that
 * the runner already computed (`report.urlNames`); falls back to
 * `deriveUrlName` so older fixtures and callers without that field
 * keep working.
 */
export function resolveUrlName(report: AiRunReport, url: string): string {
  const hit = report.urlNames?.find((u) => u.url === url);
  return hit?.name ?? deriveUrlName(url);
}

export function collectNamedUrls(report: AiRunReport): Map<string, string> {
  const out = new Map<string, string>();
  for (const s of report.steps ?? []) {
    for (const c of s.playwrightCalls ?? []) {
      if (c.method === "page.goto" && c.args?.[0]) {
        const url = String(c.args[0]);
        const name = resolveUrlName(report, url);
        if (!out.has(name)) out.set(name, url);
      }
    }
  }
  return out;
}

export function collectAllUrlNamesFromAppsettings(
  json: Record<string, unknown> | null,
): string[] {
  if (!json) return [];
  const urls = json["Urls"];
  if (!urls || typeof urls !== "object") return [];
  return Object.keys(urls as Record<string, unknown>).filter(
    (k) => /^[A-Za-z_][A-Za-z0-9_]*$/.test(k),
  );
}

export function findFirstGotoUrl(steps: AiRunStep[]): string | null {
  for (const s of steps) {
    for (const c of s.playwrightCalls ?? []) {
      if (c.method === "page.goto" && c.args?.[0]) {
        return String(c.args[0]);
      }
    }
  }
  return null;
}

export function inferFieldName(step: AiRunStep): string | null {
  if (step.inputs && step.inputs.length > 0 && step.inputs[0]?.field) {
    return step.inputs[0].field;
  }
  // Strip leading verb from method name to recover the field name.
  const name = step.method?.name ?? "";
  return name.replace(/^(Fill|Enter|Type|Set)/, "") || null;
}
