import fs from "node:fs/promises";
import { suiteKebab } from "./naming";

/** Relative path to a recorded test class file, e.g. `tests/Login.spec.ts`. */
export function testFileRelPath(className: string): string {
  return `tests/${className}.spec.ts`;
}

export function selectorsFileRelPath(suiteName: string): string {
  return `pages/selectors/${suiteName}Selectors.ts`;
}

export function actionsFileRelPath(suiteName: string): string {
  return `pages/actions/${suiteName}Actions.ts`;
}

/** `constants/{kebab}.constants.ts` — per-suite recorded constants. */
export function suiteConstantsRelPath(suiteName: string): string {
  return `constants/${suiteKebab(suiteName)}.constants.ts`;
}

/** `test-categories/{kebab}.categories.ts`. */
export function suiteCategoriesRelPath(suiteName: string): string {
  return `test-categories/${suiteKebab(suiteName)}.categories.ts`;
}

export async function readIfExists(absPath: string): Promise<string | null> {
  try {
    return await fs.readFile(absPath, "utf8");
  } catch {
    return null;
  }
}

