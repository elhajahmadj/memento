import fs from "node:fs/promises";
import { renderNodeSpec, type NodeSpecArgs } from "./renderers";

/**
 * Append a freshly-rendered AI-authored `test(...)` into an existing
 * Playwright spec file. Imports from the new spec are merged into the
 * existing import block (deduped); the test call is appended at EOF
 * preceded by a single blank-line separator and the AI-Agent header
 * comment so reviewers can see which run authored the addition.
 */
export async function appendToExistingNodeSpec(
  absPath: string,
  runId: string,
  args: NodeSpecArgs,
): Promise<void> {
  const fullRendered = renderNodeSpec(args);
  const { imports, body } = splitNodeSpecRendered(fullRendered);
  const existing = await fs.readFile(absPath, "utf8");
  const merged = mergeNodeImports(existing, imports);
  const trimmed = merged.replace(/\s+$/, "");
  const addition = [
    "",
    "",
    `// generated by Memento AI Agent — run ${runId}`,
    body.trim(),
    "",
  ].join("\n");
  await fs.writeFile(absPath, trimmed + addition);
}

/**
 * Split a freshly-rendered Node spec into its top-of-file import
 * block and the rest (header comments + test/hook call). The
 * renderer always emits `header\n\nimports\n\nbody`, so we walk past
 * the header comments, collect contiguous `import …` lines, then
 * treat everything after the blank separator as the body.
 */
export function splitNodeSpecRendered(rendered: string): {
  imports: string[];
  body: string;
} {
  const lines = rendered.split("\n");
  const imports: string[] = [];
  const bodyLines: string[] = [];
  let inImports = false;
  let afterImports = false;
  for (let i = 0; i < lines.length; i++) {
    const ln = lines[i]!;
    if (afterImports) {
      bodyLines.push(ln);
      continue;
    }
    const trimmed = ln.trim();
    if (!inImports) {
      if (trimmed.startsWith("//") || trimmed === "") continue;
      if (trimmed.startsWith("import ")) {
        inImports = true;
        imports.push(trimmed);
        continue;
      }
      bodyLines.push(...lines.slice(i));
      afterImports = true;
      continue;
    }
    if (trimmed.startsWith("import ")) {
      imports.push(trimmed);
      continue;
    }
    if (trimmed === "") continue;
    bodyLines.push(...lines.slice(i));
    afterImports = true;
  }
  return { imports, body: bodyLines.join("\n") };
}

/**
 * Add any imports from `additions` that are not already present in
 * `existing` (line-equal match, ignoring whitespace).
 */
export function mergeNodeImports(existing: string, additions: string[]): string {
  if (additions.length === 0) return existing;
  const lines = existing.split("\n");
  const present = new Set<string>();
  let lastImportIdx = -1;
  for (let i = 0; i < lines.length; i++) {
    const t = lines[i]!.trim();
    if (t.startsWith("import ")) {
      present.add(t);
      lastImportIdx = i;
    }
  }
  const missing = additions.filter((a) => !present.has(a));
  if (missing.length === 0) return existing;
  if (lastImportIdx === -1) {
    return missing.join("\n") + "\n\n" + existing;
  }
  lines.splice(lastImportIdx + 1, 0, ...missing);
  return lines.join("\n");
}
