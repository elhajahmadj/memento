import path from "node:path";
import fs from "node:fs/promises";
import type { AiRunStep } from "@/features/ai-agent/domain/types";

export function nodeHeader(runId: string): string {
  return [
    `// generated by Memento AI Agent — run ${runId}`,
    `// do not edit by hand; rerun the AI Agent to refresh.`,
  ].join("\n");
}

export function firstGotoUrl(steps: AiRunStep[]): string | null {
  for (const s of steps) {
    for (const c of s.playwrightCalls ?? []) {
      if (c.method === "page.goto" && c.args && typeof c.args[0] === "string") {
        return c.args[0];
      }
    }
  }
  return null;
}

export function inferFieldName(step: AiRunStep): string | null {
  if (step.inputs && step.inputs[0]) return step.inputs[0].field;
  const m = step.method?.name?.match(/(?:Fill|Set)([A-Z][A-Za-z0-9]*)/);
  return m ? m[1] : null;
}

export function stripSuiteSuffix(s: string): string {
  return s.replace(/Tests?$/i, "");
}

export function pascal(s: string): string {
  const parts = (s ?? "").replace(/[^a-zA-Z0-9]+/g, " ").trim().split(/\s+/);
  return parts.map((w) => (w ? w.charAt(0).toUpperCase() + w.slice(1) : "")).join("");
}

export function camel(s: string): string {
  const p = pascal(s);
  return p ? p.charAt(0).toLowerCase() + p.slice(1) : "";
}

export function kebab(s: string): string {
  return (s ?? "")
    .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
    .replace(/[^a-zA-Z0-9]+/g, "-")
    .toLowerCase()
    .replace(/^-+|-+$/g, "");
}

export function upperSnake(s: string): string {
  return (s ?? "")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^a-zA-Z0-9]+/g, "_")
    .toUpperCase()
    .replace(/^_+|_+$/g, "");
}

export function escapeTs(v: unknown): string {
  if (v == null) return "";
  return String(v).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

export async function exists(p: string): Promise<boolean> {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

export async function writeFile(abs: string, content: string): Promise<void> {
  await fs.mkdir(path.dirname(abs), { recursive: true });
  await fs.writeFile(abs, content.endsWith("\n") ? content : content + "\n");
}

/**
 * Convert a PascalCase URL name (e.g. `GoogleBaseUrl`) into the
 * UPPER_SNAKE_CASE constant we emit in `tests/config.ts`
 * (e.g. `GOOGLE_BASE_URL`). Plain `BaseUrl` becomes `BASE_URL`.
 */
export function nodeConstName(pascalName: string): string {
  return pascalName
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1_$2")
    .toUpperCase();
}

/**
 * Compute the `.setup` sidecar path for a Node spec file.
 * `tests/login.spec.ts` → `tests/login.spec.setup`.
 */
export function nodeSetupSidecarPath(specRel: string): string {
  const dir = path.posix.dirname(specRel);
  const base = path.posix.basename(specRel);
  const stem = base.endsWith(".ts") ? base.slice(0, -3) : base;
  return dir === "." ? `${stem}.setup` : `${dir}/${stem}.setup`;
}
