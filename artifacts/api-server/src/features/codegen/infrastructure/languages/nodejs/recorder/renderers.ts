import type { AiRunReport, AiRunStep } from "@/features/ai-agent/domain/types";
import { deriveUrlName } from "@/features/ai-agent/infrastructure/urlNaming";
import {
  camel,
  escapeTs,
  firstGotoUrl,
  inferFieldName,
  nodeConstName,
  upperSnake,
} from "./helpers";
import {
  collectNodeConstants,
  collectNodePageMethods,
  type NodeMethod,
} from "./collectors";

export function renderNodePage(
  pascalName: string,
  methods: NodeMethod[],
  isAdditions: boolean,
): string {
  const className = isAdditions ? `${pascalName}PageAiAdditions` : `${pascalName}Page`;
  const importLine = isAdditions
    ? `import { ${pascalName}Page } from "./${pascalName}Page";\nimport type { Page } from "@playwright/test";`
    : `import type { Page } from "@playwright/test";`;
  const extendsClause = isAdditions ? ` extends ${pascalName}Page` : "";
  const ctor = isAdditions
    ? ""
    : [
        "  constructor(public readonly page: Page) {}",
        "",
      ].join("\n");
  const body = methods
    .map((m) => {
      const sig = m.param
        ? `  async ${m.name}(${m.param}): Promise<void> {`
        : `  async ${m.name}(): Promise<void> {`;
      return [sig, ...m.body, "  }", ""].join("\n");
    })
    .join("\n");
  return `${importLine}\n\nexport class ${className}${extendsClause} {\n${ctor}${body}}\n`;
}

export function renderNodeConstants(consts: Map<string, string>): string {
  const lines: string[] = [];
  for (const [k, v] of consts.entries()) {
    lines.push(`export const ${k} = "${escapeTs(v)}";`);
  }
  return lines.join("\n") + "\n";
}

export interface NodeSpecArgs {
  runId: string;
  suitePascal: string;
  suiteKebab: string;
  kind: "playwright" | "api" | "unit";
  steps: AiRunStep[];
  report: AiRunReport;
  methodName: string;
  targetMethod: "test" | "beforeEach" | "oneTimeSetUp";
  ignore: boolean;
  ignoreReason: string | null;
}

/**
 * Map the language-agnostic targetMethod onto the @playwright/test
 * dispatcher. `beforeEach` → `test.beforeEach`, `oneTimeSetUp` →
 * `test.beforeAll`. Plain test methods honor `ignore=true` via
 * `test.skip`. Hook targets cannot be ignored — the runner rejects
 * that combination upstream.
 */
export function nodeOpenerFor(
  target: NodeSpecArgs["targetMethod"],
  ignore: boolean,
  title: string,
  reason: string | null,
): { open: string; close: string } {
  if (target === "beforeEach") {
    return { open: `test.beforeEach(async ({ page }) => {`, close: `});` };
  }
  if (target === "oneTimeSetUp") {
    return {
      open: `test.beforeAll(async ({ browser }) => {\n  const page = await browser.newPage();`,
      close: `  await page.close();\n});`,
    };
  }
  if (ignore) {
    const safe = (reason ?? "ignored by AI Agent").replace(/"/g, '\\"');
    return {
      open: `test.skip("${title}", async ({ page }) => {\n  test.skip(true, "${safe}");`,
      close: `});`,
    };
  }
  return { open: `test("${title}", async ({ page }) => {`, close: `});` };
}

export function renderNodeSpec(args: NodeSpecArgs): string {
  const header = nodeHeader(args.runId);
  if (args.kind === "api") return renderNodeApi(args, header);
  if (args.kind === "unit") return renderNodeUnit(args, header);
  return renderNodePlaywright(args, header);
}

function nodeHeader(runId: string): string {
  return [
    `// generated by Memento AI Agent — run ${runId}`,
    `// do not edit by hand; rerun the AI Agent to refresh.`,
  ].join("\n");
}

function renderNodePlaywright(args: NodeSpecArgs, header: string): string {
  const stmts: string[] = [];
  const methods = collectNodePageMethods(args.steps);
  const hasPage = methods.length > 0;
  const consts = collectNodeConstants(args.steps);
  const hasConsts = consts.size > 0;
  const goto = firstGotoUrl(args.steps);
  const namedConst = goto
    ? nodeConstName(
        args.report.urlNames?.find((u) => u.url === goto)?.name ??
          deriveUrlName(goto),
      )
    : null;

  let pageVar: string | null = null;
  if (hasPage) {
    pageVar = "po";
    stmts.push(`  const ${pageVar} = new ${args.suitePascal}Page(page);`);
  }
  if (goto && namedConst) stmts.push(`  await page.goto(config.${namedConst});`);

  for (const step of args.steps) {
    stmts.push(`  // ${step.input}`);
    let emitted = false;
    for (const c of step.playwrightCalls ?? []) {
      if (c.method === "page.goto") {
        emitted = true;
        continue;
      }
      const verb = camel(step.method?.name ?? "");
      if (!verb || !pageVar) continue;
      if (c.method === "page.click" || c.method === "expect.toBeVisible") {
        stmts.push(`  await ${pageVar}.${verb}();`);
        emitted = true;
      } else if (c.method === "page.fill") {
        const constName = upperSnake(inferFieldName(step) ?? "value") || "VALUE";
        stmts.push(`  await ${pageVar}.${verb}(${constName});`);
        emitted = true;
      }
    }
    if (!emitted) stmts.push(`  // (unrecognised — review manually)`);
  }

  const imports: string[] = [`import { test } from "@playwright/test";`];
  if (goto && namedConst) imports.push(`import * as config from "./config";`);
  if (hasPage) {
    imports.push(`import { ${args.suitePascal}Page } from "../pages/${args.suitePascal}Page";`);
  }
  if (hasConsts) {
    const names = Array.from(consts.keys()).join(", ");
    imports.push(`import { ${names} } from "./constants/${args.suiteKebab}-constants";`);
  }

  const title = `${escapeTs(args.methodName || `${args.suitePascal} (AI authored)`)}`;
  const { open, close } = nodeOpenerFor(args.targetMethod, args.ignore, title, args.ignoreReason);
  return [
    header,
    "",
    imports.join("\n"),
    "",
    open,
    ...stmts,
    close,
    "",
  ].join("\n");
}

function renderNodeApi(args: NodeSpecArgs, header: string): string {
  const stmts: string[] = [];
  for (const step of args.steps) {
    stmts.push(`  // ${step.input}`);
    for (const c of step.httpCalls ?? []) {
      const m = (c.method || "GET").toLowerCase();
      if (m === "assert") {
        if (c.status) stmts.push(`  expect(response.status()).toBe(${c.status});`);
        continue;
      }
      stmts.push(`  response = await request.${m}("${escapeTs(c.url)}");`);
      if (c.status) stmts.push(`  expect(response.status()).toBe(${c.status});`);
    }
  }
  const title = `${escapeTs(args.methodName || `${args.suitePascal} API (AI authored)`)}`;
  const fn =
    args.targetMethod === "beforeEach"
      ? "test.beforeEach"
      : args.targetMethod === "oneTimeSetUp"
        ? "test.beforeAll"
        : args.ignore
          ? "test.skip"
          : "test";
  const open =
    args.targetMethod === "test"
      ? `${fn}("${title}", async ({ request }) => {`
      : `${fn}(async ({ request }) => {`;
  const skipLine =
    args.targetMethod === "test" && args.ignore
      ? [`  test.skip(true, "${escapeTs((args.ignoreReason ?? "").trim() || "ignored by AI Agent")}");`]
      : [];
  return [
    header,
    "",
    `import { test, expect, type APIResponse } from "@playwright/test";`,
    "",
    open,
    ...skipLine,
    `  let response: APIResponse = null as unknown as APIResponse;`,
    ...stmts,
    "});",
    "",
  ].join("\n");
}

function renderNodeUnit(args: NodeSpecArgs, header: string): string {
  const stmts: string[] = [];
  for (const step of args.steps) {
    stmts.push(`  // ${step.input}`);
    for (const c of step.unitCalls ?? []) {
      const fn = camel(c.function);
      const a = c.args.map((x) => JSON.stringify(x)).join(", ");
      stmts.push(`  expect(${fn}(${a})).toEqual(${JSON.stringify(c.expected)});`);
    }
  }
  const title = `${escapeTs(args.methodName || `${args.suitePascal} unit (AI authored)`)}`;
  const fn =
    args.targetMethod === "beforeEach"
      ? "test.beforeEach"
      : args.targetMethod === "oneTimeSetUp"
        ? "test.beforeAll"
        : args.ignore
          ? "test.skip"
          : "test";
  const open =
    args.targetMethod === "test"
      ? `${fn}("${title}", () => {`
      : `${fn}(() => {`;
  const skipLine =
    args.targetMethod === "test" && args.ignore
      ? [`  test.skip(true, "${escapeTs((args.ignoreReason ?? "").trim() || "ignored by AI Agent")}");`]
      : [];
  return [
    header,
    "",
    `import { test, expect } from "@playwright/test";`,
    "",
    open,
    ...skipLine,
    ...stmts,
    "});",
    "",
  ].join("\n");
}
