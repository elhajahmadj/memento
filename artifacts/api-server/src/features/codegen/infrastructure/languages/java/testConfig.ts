// TestConfig.<NAME> regeneration (typed URL accessor — task #207).
import fs from "node:fs/promises";
import { safeJoin } from "@/features/projects/infrastructure/paths";
import type { Project } from "@/features/projects/domain/types";
import { applyTokens } from "@/features/codegen/infrastructure/templates";
import { JAVA_TEST_CONFIG_CONTENT } from "@/features/architectures/infrastructure/architectureService";
import { pkgPath, sharedModuleDir } from "./paths";

const JAVA_URL_BLOCK_OPEN = "// <auto-generated-urls>";
const JAVA_URL_BLOCK_CLOSE = "// </auto-generated-urls>";

/** Relative path to the scaffold-emitted Java TestConfig file. */
function javaTestConfigRelPath(project: Project): string {
  return `${sharedModuleDir(project)}/src/main/java/${pkgPath(project)}/TestConfig.java`;
}

/**
 * Rewrite the `<auto-generated-urls>` block inside `TestConfig.java`
 * with one `public static final String NAME = AppConfiguration.get(...);`
 * field per `.env` URL key. `AppConfiguration` already merges env-vars
 * with the local `.env` file so the constant is hot at class-load time.
 * Returns the relative path written, or `null` when the scaffold file is
 * missing.
 */
export async function regenerateTestConfig(
  project: Project,
  urlNames: string[],
  solutionName: string,
): Promise<string | null> {
  const rel = javaTestConfigRelPath(project);
  const abs = safeJoin(project.rootPath, rel);
  const safeSolution = solutionName
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, "_");
  const sorted = [...new Set(urlNames)].sort();
  const innerLines = sorted.map(
    (n) =>
      `    public static final String ${n} = AppConfiguration.get("${safeSolution}_URL_${n}");`,
  );

  let original: string | null = null;
  try {
    original = await fs.readFile(abs, "utf8");
  } catch {
    // file missing — fall through to template materialization
  }

  // Legacy compatibility: a Java project scaffolded before task #207
  // has no `TestConfig.java` at all (the C# / Python / Node analogues
  // existed earlier). Materialize the canonical template so the
  // generated test class's `import <pkg>.TestConfig;` resolves.
  if (
    original === null ||
    !original.includes(JAVA_URL_BLOCK_OPEN) ||
    !original.includes(JAVA_URL_BLOCK_CLOSE)
  ) {
    const path = await import("node:path");
    try {
      await fs.mkdir(path.dirname(abs), { recursive: true });
    } catch {
      return null;
    }
    let rendered = applyTokens(JAVA_TEST_CONFIG_CONTENT, {
      namespace: project.namespace,
      solution: project.solutionName,
      package: pkgPath(project),
    });
    rendered = replaceMarkerBlockJava(
      rendered,
      JAVA_URL_BLOCK_OPEN,
      JAVA_URL_BLOCK_CLOSE,
      innerLines,
    );
    if (sorted.length > 0) {
      rendered = ensureJavaImport(
        rendered,
        `import ${pkgPath(project)}.AppConfiguration;`,
      );
    }
    await fs.writeFile(abs, rendered);
    return rel;
  }

  let next = replaceMarkerBlockJava(
    original,
    JAVA_URL_BLOCK_OPEN,
    JAVA_URL_BLOCK_CLOSE,
    innerLines,
  );
  if (sorted.length > 0) {
    next = ensureJavaImport(
      next,
      `import ${pkgPath(project)}.AppConfiguration;`,
    );
  }
  if (next === original) return rel;
  await fs.writeFile(abs, next);
  return rel;
}

function replaceMarkerBlockJava(
  original: string,
  openMarker: string,
  closeMarker: string,
  innerLines: string[],
): string {
  const lines = original.split(/\r?\n/);
  let openIdx = -1;
  let closeIdx = -1;
  for (let i = 0; i < lines.length; i++) {
    if (lines[i]!.includes(openMarker)) {
      openIdx = i;
      for (let j = i + 1; j < lines.length; j++) {
        if (lines[j]!.includes(closeMarker)) {
          closeIdx = j;
          break;
        }
      }
      break;
    }
  }
  if (openIdx === -1 || closeIdx === -1) return original;
  const next = [
    ...lines.slice(0, openIdx + 1),
    ...innerLines,
    ...lines.slice(closeIdx),
  ];
  return next.join("\n");
}

function ensureJavaImport(source: string, importLine: string): string {
  const lines = source.split(/\r?\n/);
  if (lines.some((l) => l.trim() === importLine)) return source;
  let pkgIdx = -1;
  for (let i = 0; i < lines.length; i++) {
    if (/^\s*package\s+/.test(lines[i]!)) {
      pkgIdx = i;
      break;
    }
  }
  const insertAt = pkgIdx >= 0 ? pkgIdx + 1 : 0;
  // Add a blank separator after the package line (keeps Java style).
  const separator = pkgIdx >= 0 && lines[insertAt]?.trim() !== "" ? [""] : [];
  const next = [
    ...lines.slice(0, insertAt),
    ...separator,
    importLine,
    ...lines.slice(insertAt),
  ];
  return next.join("\n");
}
