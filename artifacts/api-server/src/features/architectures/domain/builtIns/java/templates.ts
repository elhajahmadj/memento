export const JAVA_APP_CONFIGURATION_CONTENT = `package {{Package}};

import io.github.cdimascio.dotenv.Dotenv;

/** Reads configuration from environment variables, falling back to a local .env file. */
public final class AppConfiguration {
    private static final Dotenv DOTENV = Dotenv.configure().ignoreIfMissing().load();

    private AppConfiguration() {}

    public static String get(String key) {
        return get(key, null);
    }

    public static String get(String key, String defaultValue) {
        String envValue = System.getenv(key);
        if (envValue != null && !envValue.isEmpty()) return envValue;
        String dotenvValue = DOTENV.get(key);
        if (dotenvValue != null && !dotenvValue.isEmpty()) return dotenvValue;
        return defaultValue;
    }

    public static int getInt(String key, int defaultValue) {
        String value = get(key);
        if (value == null) return defaultValue;
        try {
            return Integer.parseInt(value);
        } catch (NumberFormatException e) {
            return defaultValue;
        }
    }

    public static boolean getBool(String key, boolean defaultValue) {
        String value = get(key);
        if (value == null) return defaultValue;
        return value.equalsIgnoreCase("true") || value.equals("1") || value.equalsIgnoreCase("yes");
    }

    public static boolean isLocalEnv() {
        String env = get("ENVIRONMENT", "local");
        return env.equalsIgnoreCase("local") || env.equalsIgnoreCase("dev");
    }
}
`;

