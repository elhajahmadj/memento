export const JAVA_BROWSER_MANAGER_CONTENT = `package {{Package}}.infrastructure;

import com.microsoft.playwright.Browser;
import com.microsoft.playwright.BrowserContext;
import com.microsoft.playwright.BrowserType;
import com.microsoft.playwright.Page;
import com.microsoft.playwright.Playwright;
import com.microsoft.playwright.Tracing;

import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;

import {{Package}}.AppConfiguration;
import {{Package}}.TestOutputLogger;

/** Owns the Playwright browser lifecycle plus screenshot and tracing helpers. */
public class BrowserManager implements AutoCloseable {
    private static final DateTimeFormatter TS = DateTimeFormatter.ofPattern("yyyyMMdd_HHmmss");

    private final Playwright playwright;
    private final Browser browser;
    private final TestOutputLogger logger = new TestOutputLogger();
    private boolean tracingStarted = false;

    public BrowserManager() {
        this.playwright = Playwright.create();
        boolean headless = AppConfiguration.getBool("HEADLESS", true);
        BrowserType.LaunchOptions opts = new BrowserType.LaunchOptions().setHeadless(headless);
        this.browser = playwright.chromium().launch(opts);
    }

    public BrowserContext newContext() {
        Browser.NewContextOptions ctxOpts = new Browser.NewContextOptions()
            .setViewportSize(1280, 720)
            .setIgnoreHTTPSErrors(true);
        BrowserContext context = browser.newContext(ctxOpts);
        context.setDefaultTimeout(AppConfiguration.getInt("PLAYWRIGHT_TIMEOUT_MS", 30_000));
        return context;
    }

    public Page newPage(BrowserContext context) {
        return context.newPage();
    }

    public Path takeScreenshot(Page page, String testName) {
        try {
            Path outDir = Paths.get("test-results");
            Files.createDirectories(outDir);
            Path target = outDir.resolve(testName + "_" + LocalDateTime.now().format(TS) + ".png");
            page.screenshot(new Page.ScreenshotOptions().setPath(target).setFullPage(true));
            logger.logScreenshot(target.toString());
            return target;
        } catch (Exception e) {
            logger.error("Screenshot failed: " + e.getMessage());
            return null;
        }
    }

    public void startTracing(BrowserContext context) {
        try {
            context.tracing().start(new Tracing.StartOptions()
                .setScreenshots(true)
                .setSnapshots(true)
                .setSources(true));
            tracingStarted = true;
        } catch (Exception e) {
            logger.error("Failed to start tracing: " + e.getMessage());
        }
    }

    public Path stopTracing(BrowserContext context, String testName) {
        if (!tracingStarted) return null;
        try {
            Path outDir = Paths.get("test-results");
            Files.createDirectories(outDir);
            Path target = outDir.resolve(testName + "_" + LocalDateTime.now().format(TS) + ".zip");
            context.tracing().stop(new Tracing.StopOptions().setPath(target));
            logger.logTrace(target.toString());
            tracingStarted = false;
            return target;
        } catch (Exception e) {
            logger.error("Failed to stop tracing: " + e.getMessage());
            return null;
        }
    }

    public static boolean shouldStartTracing() {
        return AppConfiguration.getBool("START_TRACER", false);
    }

    @Override
    public void close() {
        try { browser.close(); } catch (Exception ignored) {}
        try { playwright.close(); } catch (Exception ignored) {}
    }
}
`;

