import path from "node:path";
import fs from "node:fs/promises";
import type { AiRunStep } from "@/features/ai-agent/domain/types";

export function javaHeader(runId: string): string {
  return [
    `// generated by Memento AI Agent — run ${runId}`,
    `// do not edit by hand; rerun the AI Agent to refresh.`,
  ].join("\n");
}

export function firstGotoUrl(steps: AiRunStep[]): string | null {
  for (const s of steps) {
    for (const c of s.playwrightCalls ?? []) {
      if (c.method === "page.goto" && c.args && typeof c.args[0] === "string") {
        return c.args[0];
      }
    }
  }
  return null;
}

export function inferFieldName(step: AiRunStep): string | null {
  if (step.inputs && step.inputs[0]) return step.inputs[0].field;
  const m = step.method?.name?.match(/(?:Fill|Set)([A-Z][A-Za-z0-9]*)/);
  return m ? m[1] : null;
}

export function stripSuiteSuffix(s: string): string {
  return s.replace(/Tests?$/i, "");
}

export function pascal(s: string): string {
  const parts = (s ?? "").replace(/[^a-zA-Z0-9]+/g, " ").trim().split(/\s+/);
  return parts.map((w) => (w ? w.charAt(0).toUpperCase() + w.slice(1) : "")).join("");
}

export function camel(s: string): string {
  const p = pascal(s);
  return p ? p.charAt(0).toLowerCase() + p.slice(1) : "";
}

export function upperSnake(s: string): string {
  return (s ?? "")
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/[^a-zA-Z0-9]+/g, "_")
    .toUpperCase()
    .replace(/^_+|_+$/g, "");
}

export function escapeJ(v: unknown): string {
  if (v == null) return "";
  return String(v).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

export async function exists(p: string): Promise<boolean> {
  try {
    await fs.access(p);
    return true;
  } catch {
    return false;
  }
}

export async function writeFile(abs: string, content: string): Promise<void> {
  await fs.mkdir(path.dirname(abs), { recursive: true });
  await fs.writeFile(abs, content.endsWith("\n") ? content : content + "\n");
}

export function parseJavaPackage(src: string): string | null {
  const m = src.match(/^\s*package\s+([\w.]+)\s*;/m);
  return m?.[1] ?? null;
}

export function parseJavaDeclaredClass(src: string): string | null {
  // Skip imports + comments; find the first top-level `class …` decl
  // that isn't `abstract`. Mirrors the test-discovery parser rule.
  const re =
    /(?:^|\n)(?:[ \t]*(?:@[\w.]+(?:\s*\([^)]*\))?\s*\n)?)*[ \t]*((?:public|protected|private)\s+)?((?:final|static)\s+)*((?:abstract)\s+)?class\s+([A-Za-z_]\w*)/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(src)) !== null) {
    if (m[3]) continue; // abstract
    return m[4] ?? null;
  }
  return null;
}

/**
 * Derive the "root" package (e.g. `demo`) from a tests-folder package
 * (`demo.tests` or `demo.subarea.tests`). Falls back to the input
 * package when it doesn't end in `.tests`.
 */
export function rootPackageFromTestsPackage(pkg: string): string {
  if (pkg.endsWith(".tests")) return pkg.slice(0, -".tests".length);
  return pkg;
}

export function javaPackageName(s: string): string {
  const cleaned = (s ?? "").replace(/[^A-Za-z0-9]/g, "").toLowerCase();
  if (!cleaned) return "pkg";
  if (/^[0-9]/.test(cleaned)) return `pkg${cleaned}`;
  return cleaned;
}

/**
 * Convert a PascalCase URL name (e.g. `GoogleBaseUrl`) into the
 * dotted property key we emit in `application.properties`
 * (e.g. `google.base.url`). Plain `BaseUrl` becomes `base.url`.
 */
export function javaPropertyKey(pascalName: string): string {
  return pascalName
    .replace(/([a-z0-9])([A-Z])/g, "$1.$2")
    .replace(/([A-Z]+)([A-Z][a-z])/g, "$1.$2")
    .toLowerCase();
}

/**
 * `GoogleBaseUrl` -> `getGoogleBaseUrl`. Used by the generated test class
 * to read the typed URL via `new Config().getGoogleBaseUrl()`.
 */
export function javaConfigGetterName(pascalName: string): string {
  if (!pascalName) return "getBaseUrl";
  return `get${pascalName.charAt(0).toUpperCase()}${pascalName.slice(1)}`;
}
