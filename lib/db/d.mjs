import pg from "pg";
const c = new pg.Client({ connectionString: process.env.DATABASE_URL });
await c.connect();
const r = await c.query(`SELECT current_database() db, current_schema() schema`);
console.log(r.rows);
const t = await c.query(`SELECT table_schema, table_name FROM information_schema.tables WHERE table_name='ai_runs'`);
console.log("ai_runs locations:", t.rows);
const all = await c.query(`SELECT table_name FROM information_schema.tables WHERE table_schema='public' ORDER BY 1`);
console.log("public tables:", all.rows.map(r=>r.table_name).join(", "));
await c.end();
